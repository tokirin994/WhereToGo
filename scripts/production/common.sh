#!/usr/bin/env bash
# Source from another production script; paths are always relative to this checkout.
set -Eeuo pipefail
REPO="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)"
RUNTIME="$REPO/.local/production"
[[ $EUID -eq 0 ]] || { echo 'Run with sudo on the Linux production server.' >&2; exit 1; }
[[ -f "$RUNTIME/.env" && ! -L "$RUNTIME/.env" ]] || { echo 'Generate production settings first.' >&2; exit 1; }
[[ $(stat -c '%u' "$RUNTIME/.env") == 0 ]] || { echo 'Production settings must be owned by root.' >&2; exit 1; }
if (( (8#$(stat -c '%a' "$RUNTIME/.env") & 8#022) != 0 )); then
  echo 'Production settings cannot be writable by group or other users.' >&2; exit 1
fi
cd -- "$REPO"
# This is the root-owned configuration generated by prepare.py, not downloaded/untrusted input.
set -a
source "$RUNTIME/.env"
set +a
dc() { docker compose --env-file "$RUNTIME/.env" --file "$REPO/deploy/production/compose.yml" "$@"; }
need() { command -v "$1" >/dev/null || { echo "Install required command: $1" >&2; exit 1; }; }
wait_https() {
  local address="$1" attempts=90
  until curl --proto '=https' --tlsv1.2 --fail --silent --show-error --max-time 10 "$address" >/dev/null 2>&1; do
    attempts=$((attempts - 1))
    (( attempts > 0 )) || { echo "Service not ready: $address. Check DNS, firewall and docker compose logs." >&2; return 1; }
    sleep 3
  done
}
